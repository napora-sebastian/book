/* Polish.

   Keys are the English text exactly as it stands in the markup. A phrase that
   the interface shows both shouted and spoken — SAVE SOURCES in the deck's HUD,
   "Save sources" in the lab — needs one entry only, in sentence case: i18n.js
   folds the caps down to find it and shouts the answer back. Leading glyphs
   (⁂, ✎, ←) are handled the same way and are not part of any key.

   Vocabulary held steady on purpose, because the same object is called three
   things by three views: thread → wątek, record → zapis, conversation →
   rozmowa, book → księga, graph → graf, point → punkt, source → źródło,
   version → wersja.

   REMOVE and DELETE typed into a confirmation box are NOT translated — the code
   compares against those literal words. Their inputs carry data-i18n-skip. */

/* Polish counts in three forms, and a table of fixed strings cannot hold that:
   1 graf, 2 grafy, 5 grafów. Anything with a number in front of it goes through
   here instead. */
const n3 = (n, one, few, many) => {
  const i = Math.abs(Number(n));
  if (i === 1) return one;
  const last = i % 10;
  const teens = i % 100 >= 12 && i % 100 <= 14;
  return last >= 2 && last <= 4 && !teens ? few : many;
};
/* Same word, shouted, when the deck's HUD is the caller. */
const up = (fn) => (...args) => fn(...args).toUpperCase();
const count = (one, few, many) => (m, n) => `${n} ${n3(n, one, few, many)}`;

